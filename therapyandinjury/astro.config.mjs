// @ts-check
import { defineConfig } from 'astro/config';
import node from '@astrojs/node';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const site = JSON.parse(readFileSync(new URL('./src/data/site.json', import.meta.url), 'utf8'));
const branches = JSON.parse(readFileSync(new URL('./src/data/branches.json', import.meta.url), 'utf8'));

/**
 * Writes dist/.htaccess for Apache (Namecheap cPanel). City domains listed in
 * branches.json redirect to their branch page, so adding a domain is a data change.
 */
function htaccess() {
  return {
    name: 'htaccess',
    hooks: {
      'astro:build:done': ({ dir }) => {
        const host = new URL(site.domain).host.replace(/\./g, '\\.');
        const cityRules = branches
          .flatMap((b) =>
            (b.domains ?? []).map(
              (d) =>
                `RewriteCond %{HTTP_HOST} ^(www\\.)?${d.replace(/\./g, '\\.')}$ [NC]\nRewriteRule ^ ${site.domain}/${b.slug}/ [R=301,L]`,
            ),
          )
          .join('\n\n');
        const out = `# Generated by astro.config.mjs at build time. Edit there, not here.
Options -Indexes
ErrorDocument 404 /404.html
DirectorySlash On

<IfModule mod_rewrite.c>
RewriteEngine On

# City domains -> branch pages (from branches.json "domains")
${cityRules}

# Force HTTPS and the bare domain
RewriteCond %{HTTPS} off [OR]
RewriteCond %{HTTP_HOST} ^www\\. [NC]
RewriteRule ^ ${site.domain}%{REQUEST_URI} [R=301,L]
RewriteCond %{HTTP_HOST} !^${host}$ [NC]
RewriteCond %{HTTP_HOST} !^localhost [NC]
RewriteRule ^ ${site.domain}%{REQUEST_URI} [R=301,L]
</IfModule>

<IfModule mod_headers.c>
Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains"
Header always set X-Content-Type-Options "nosniff"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
Header always set X-Frame-Options "SAMEORIGIN"
Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(self)"
<FilesMatch "\\.(svg|png|jpg|webp|ico)$">
Header set Cache-Control "public, max-age=86400"
</FilesMatch>
<FilesMatch "\\.(html|xml|txt)$">
Header set Cache-Control "public, max-age=600"
</FilesMatch>
# Fingerprinted build assets never change
<If "%{REQUEST_URI} =~ m#^/_astro/#">
Header set Cache-Control "public, max-age=31536000, immutable"
</If>
</IfModule>
`;
        writeFileSync(fileURLToPath(new URL('.htaccess', dir)), out);
      },
    },
  };
}

// Pages render on the server (deploy/server mounts the Astro handler), so content edited at /_admin
// shows up without a rebuild. Everything is bundled into dist/server: the release needs no node_modules.
export default defineConfig({
  site: site.domain,
  trailingSlash: 'always',
  output: 'server',
  adapter: node({ mode: 'middleware' }),
  build: { format: 'directory' },
  vite: { ssr: { noExternal: true }, define: { __BUILD_DATE__: JSON.stringify(new Date().toISOString()) } },
  integrations: [htaccess()],
});
